"""NL-to-SQL accuracy evaluation framework.

Measures execution accuracy by comparing SQL generated by the NL-to-SQL
engine against golden SQL queries. Supports tiered accuracy thresholds
(AISEM-03: 90% simple, 70% complex) with separate metrics for simple
and complex queries.

Usage:
    engine = NLToSQLEngine(model_dir="semantic/model")
    conn = get_trino_connection()
    dataset = load_golden_dataset("path/to/trading_questions.json")
    results = run_evaluation(engine, conn, dataset)
    report = generate_evaluation_report(results)
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from src.semantic.nl_to_sql import NLToSQLEngine

logger = logging.getLogger(__name__)

# Accuracy thresholds from AISEM-03
SIMPLE_THRESHOLD = 90.0
COMPLEX_THRESHOLD = 70.0


@dataclass
class EvalResult:
    """Result of evaluating a single NL-to-SQL question.

    Attributes:
        question: The natural language question.
        golden_sql: The reference SQL from the golden dataset.
        generated_sql: The SQL generated by the NL-to-SQL engine.
        golden_results: Result set from executing golden_sql.
        generated_results: Result set from executing generated_sql.
        match: Whether the result sets match (order-independent).
        complexity: 'simple' or 'complex' classification.
        error: Error message if generated SQL failed execution, else None.
    """

    question: str
    golden_sql: str
    generated_sql: str
    golden_results: list[tuple]
    generated_results: list[tuple]
    match: bool
    complexity: str
    error: str | None


def load_golden_dataset(path: str) -> list[dict]:
    """Load a golden Q&A dataset from a JSON file.

    Args:
        path: Path to the JSON file containing golden question-SQL pairs.

    Returns:
        List of dicts, each with 'question', 'sql', and 'complexity' keys.
    """
    with open(path) as f:
        return json.load(f)


def evaluate_accuracy(
    results: list[EvalResult],
    complexity_filter: str | None = None,
) -> dict:
    """Compute accuracy metrics from evaluation results.

    Args:
        results: List of EvalResult from run_evaluation().
        complexity_filter: If set, only count results matching this
            complexity ('simple' or 'complex'). If None, count all.

    Returns:
        Dict with 'total', 'correct', and 'accuracy_pct' keys.
    """
    if complexity_filter:
        filtered = [r for r in results if r.complexity == complexity_filter]
    else:
        filtered = results

    total = len(filtered)
    if total == 0:
        return {"total": 0, "correct": 0, "accuracy_pct": 0.0}

    correct = sum(1 for r in filtered if r.match)
    accuracy_pct = (correct / total) * 100.0

    return {
        "total": total,
        "correct": correct,
        "accuracy_pct": round(accuracy_pct, 2),
    }


def run_evaluation(
    engine: NLToSQLEngine,
    conn: object,
    dataset: list[dict],
) -> list[EvalResult]:
    """Run NL-to-SQL evaluation against a golden dataset.

    For each golden question:
    1. Generate SQL via engine.ask()
    2. Execute both golden SQL and generated SQL against the connection
    3. Compare result sets (order-independent)
    4. Record EvalResult

    Args:
        engine: NLToSQLEngine instance for SQL generation.
        conn: Database connection with cursor() context manager.
        dataset: List of golden Q&A dicts from load_golden_dataset().

    Returns:
        List of EvalResult, one per golden question.
    """
    results: list[EvalResult] = []

    for entry in dataset:
        question = entry["question"]
        golden_sql = entry["sql"]
        complexity = entry["complexity"]

        # Generate SQL
        try:
            generated_sql = engine.ask(question)
        except Exception as exc:
            logger.warning("SQL generation failed for: %s -- %s", question, exc)
            results.append(EvalResult(
                question=question,
                golden_sql=golden_sql,
                generated_sql="",
                golden_results=[],
                generated_results=[],
                match=False,
                complexity=complexity,
                error=f"Generation failed: {exc}",
            ))
            continue

        # Execute golden SQL
        golden_results: list[tuple] = []
        try:
            with conn.cursor() as cur:
                cur.execute(golden_sql)
                golden_results = cur.fetchall()
        except Exception as exc:
            logger.warning("Golden SQL execution failed: %s -- %s", golden_sql, exc)
            golden_results = []

        # Execute generated SQL
        generated_results: list[tuple] = []
        error: str | None = None
        try:
            with conn.cursor() as cur:
                cur.execute(generated_sql)
                generated_results = cur.fetchall()
        except Exception as exc:
            logger.warning("Generated SQL execution failed: %s -- %s", generated_sql, exc)
            error = f"Execution failed: {exc}"

        # Compare results (order-independent)
        match = _compare_results(golden_results, generated_results)

        results.append(EvalResult(
            question=question,
            golden_sql=golden_sql,
            generated_sql=generated_sql,
            golden_results=golden_results,
            generated_results=generated_results,
            match=match,
            complexity=complexity,
            error=error,
        ))

    return results


def _compare_results(
    golden: list[tuple],
    generated: list[tuple],
) -> bool:
    """Compare two result sets, order-independent.

    Args:
        golden: Expected result set.
        generated: Actual result set from generated SQL.

    Returns:
        True if the sorted result sets are equal.
    """
    try:
        return sorted(golden) == sorted(generated)
    except TypeError:
        # Fallback for unhashable/uncomparable types
        return golden == generated


def generate_evaluation_report(results: list[EvalResult]) -> dict:
    """Generate a structured accuracy report from evaluation results.

    Returns overall, simple, and complex accuracy breakdowns with
    pass/fail status against AISEM-03 thresholds (90% simple, 70% complex).

    Args:
        results: List of EvalResult from run_evaluation().

    Returns:
        Dict with 'overall', 'simple', 'complex' accuracy dicts,
        'simple_pass' and 'complex_pass' booleans, and 'details' list.
    """
    overall = evaluate_accuracy(results)
    simple = evaluate_accuracy(results, complexity_filter="simple")
    complex_ = evaluate_accuracy(results, complexity_filter="complex")

    return {
        "overall": overall,
        "simple": simple,
        "complex": complex_,
        "simple_pass": simple["accuracy_pct"] >= SIMPLE_THRESHOLD,
        "complex_pass": complex_["accuracy_pct"] >= COMPLEX_THRESHOLD,
        "details": [
            {
                "question": r.question,
                "match": r.match,
                "complexity": r.complexity,
                "error": r.error,
            }
            for r in results
        ],
    }
